#!/usr/bin/env node
/**
 * Builds supabase/functions/<router>/ from base44/functions/<router>/
 * (docs/migracion-supabase.md, phase 2). Base44 stays the single source: the
 * copies are generated, git-ignored and rebuilt by CI and before every deploy,
 * so they can never drift from what Base44 serves.
 *
 *   npm run generate:supabase-functions
 *
 * What changes in a copy, and nothing else:
 * - The one SDK import (`npm:@base44/sdk@…`) points to
 *   supabase/functions/_shared/base44_compat.ts, which gives the same
 *   `createClientFromRequest` over Supabase. `_guard.ts` and every handler run
 *   unchanged.
 * - `entry.ts` becomes `router.ts`, and a generated `index.ts` serves it with
 *   CORS (`_shared/serve.ts`): Supabase's entry point is `index.ts` and calls
 *   `Deno.serve`, where Base44 took a default export.
 * - REPLACED files: Base44-only plumbing swapped for a Supabase stand-in.
 * - Each router gets a `deno.json` (`nodeModulesDir: none`).
 * - Tests (`*_test.ts`, `*.test.ts`) are not copied.
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(root, "base44", "functions");
const OUT = join(root, "supabase", "functions");
const SHARED = join(OUT, "_shared");

// Not ported: retired on Base44 (410) and never needed again.
export const SKIP = new Set(["processSale"]);

// router -> { file inside the router: template that replaces it }.
const REPLACED = {
  terminals: { "_platform.ts": join(root, "scripts", "templates", "supabase", "terminals_platform.ts") },
};

const SDK_IMPORT = /(['"])npm:@base44\/sdk@[^'"]+\1/g;

export function routers() {
  return readdirSync(SRC)
    .filter((d) => !SKIP.has(d) && existsSync(join(SRC, d, "entry.ts")))
    .sort();
}

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const isTest = (p) => /(_test|\.test)\.ts$/.test(p);

function rewrite(text, outFile) {
  let rel = relative(dirname(outFile), join(SHARED, "base44_compat.ts")).split("\\").join("/");
  if (!rel.startsWith(".")) rel = `./${rel}`;
  return text.replace(SDK_IMPORT, (_m, q) => `${q}${rel}${q}`);
}

const INDEX = `// GENERATED by scripts/generate-supabase-functions.mjs. Do not edit.
import handler from './router.ts';
import { withCors } from '../_shared/serve.ts';

Deno.serve(withCors(handler));
`;

export function generate() {
  // Start clean: a router removed from base44/functions must not linger here.
  for (const name of existsSync(OUT) ? readdirSync(OUT) : []) {
    if (name !== "_shared" && statSync(join(OUT, name)).isDirectory()) rmSync(join(OUT, name), { recursive: true });
  }
  const list = routers();
  for (const router of list) {
    const from = join(SRC, router);
    const to = join(OUT, router);
    for (const file of walk(from).filter((p) => p.endsWith(".ts") && !isTest(p))) {
      const relPath = relative(from, file);
      const outPath = join(to, relPath === "entry.ts" ? "router.ts" : relPath);
      mkdirSync(dirname(outPath), { recursive: true });
      const replacement = REPLACED[router]?.[relPath];
      const text = readFileSync(replacement ?? file, "utf8");
      writeFileSync(outPath, rewrite(text, outPath));
    }
    for (const relPath of Object.keys(REPLACED[router] ?? {})) {
      if (!existsSync(join(from, relPath))) throw new Error(`REPLACED ${router}/${relPath} no longer exists in base44/functions`);
    }
    writeFileSync(join(to, "index.ts"), INDEX);
    // npm: imports resolve from Deno's cache, never from the repo's
    // node_modules (the frontend's), which has no supabase-js.
    writeFileSync(join(to, "deno.json"), JSON.stringify({ nodeModulesDir: "none" }, null, 2) + "\n");
  }
  return list;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const list = generate();
  const config = readFileSync(join(root, "supabase", "config.toml"), "utf8");
  const unconfigured = list.filter((r) => !new RegExp(`\\[functions\\.${r}\\]\\s*\\nverify_jwt = false`).test(config));
  if (unconfigured.length) {
    console.error(`✗ supabase/config.toml has no [functions.<name>] verify_jwt = false for: ${unconfigured.join(", ")}`);
    process.exit(1);
  }
  const leftover = list
    .flatMap((r) => walk(join(OUT, r)))
    .filter((p) => /npm:@base44\/sdk/.test(readFileSync(p, "utf8").replace(/\/\/[^\n]*/g, "")))
    .map((p) => relative(OUT, p));
  if (leftover.length) {
    console.error(`✗ SDK import left in: ${leftover.join(", ")}`);
    process.exit(1);
  }
  console.log(`✓ generated ${list.length} Supabase functions in supabase/functions (${[...SKIP].join(", ")} skipped).`);
}
